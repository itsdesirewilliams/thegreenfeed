import { createAdminSupabaseClient } from "@/lib/supabase/server";
import {
  SURVEY_CONSENT_ID,
  SURVEY_PUBLISHED,
  SURVEY_PROFILE_FIELDS,
  SURVEY_SCHEMA_VERSION,
  surveyQuestions,
  type SurveyAnswerValue,
} from "@/data/survey-questions";
import {
  validateSurveyAnswers,
} from "@/lib/survey";

/**
 * Survey submission endpoint (POST /api/survey).
 *
 * Security model:
 * - The browser never talks to Supabase directly for survey inserts. This
 *   handler validates the payload and writes through the server-only secret
 *   key client (`SUPABASE_SECRET_KEY`), which bypasses RLS.
 * - RLS on `survey_submissions` allows no public SELECT/INSERT/UPDATE/DELETE,
 *   so the publishable key alone can never touch the table.
 * - `id` and `created_at` are generated by the database.
 * - Nothing submitted is echoed back, and survey answers are never logged.
 *
 * The survey stays closed (HTTP 503) until the question schema is published,
 * except for the development-only preview described in the README, which is
 * unreachable in production builds.
 */

const MAX_BODY_CHARS = 20_000;
const MAX_CHOICE_COUNT = 20;
const MAX_PROFILE_TEXT_CHARS = 200;

function jsonError(message: string, status: number) {
  return Response.json({ error: message }, { status });
}

export async function POST(request: Request) {
  const published = SURVEY_PUBLISHED && surveyQuestions.length > 0;
  const devPreview =
    process.env.NODE_ENV !== "production" &&
    process.env.SURVEY_DEV_PREVIEW === "1";

  if (!published && !devPreview) {
    return jsonError(
      "The survey is not accepting responses yet. It will open once publication is approved.",
      503,
    );
  }

  const contentType = request.headers.get("content-type") ?? "";
  if (!contentType.includes("application/json")) {
    return jsonError("Expected a JSON request.", 415);
  }

  // Basic same-origin protection: reject requests whose Origin points at a
  // different host than the one serving this API.
  const origin = request.headers.get("origin");
  const host = request.headers.get("host");
  if (origin && host) {
    try {
      if (new URL(origin).host !== host) {
        return jsonError("Cross-origin submissions are not allowed.", 403);
      }
    } catch {
      return jsonError("Invalid request origin.", 403);
    }
  }

  const text = await request.text();
  if (text.length > MAX_BODY_CHARS) {
    return jsonError("The submission is too large.", 413);
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    return jsonError("The submission is not valid JSON.", 400);
  }

  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) {
    return jsonError("Unexpected submission format.", 400);
  }

  const { answers, schemaVersion } = parsed as Record<string, unknown>;

  if (!answers || typeof answers !== "object" || Array.isArray(answers)) {
    return jsonError("Unexpected submission format.", 400);
  }

  if (schemaVersion !== undefined && schemaVersion !== SURVEY_SCHEMA_VERSION) {
    return jsonError(
      "The survey has changed. Please reload the page and try again.",
      400,
    );
  }

  const submitted = answers as Record<string, unknown>;

  // Only known keys are accepted: the 16 research questions, the consent
  // decision, and the configured respondent-profile fields.
  const allowedKeys = new Set<string>([
    SURVEY_CONSENT_ID,
    ...SURVEY_PROFILE_FIELDS.map((field) => field.id),
    ...surveyQuestions.map((question) => question.id),
  ]);
  for (const key of Object.keys(submitted)) {
    if (!allowedKeys.has(key)) {
      return jsonError("One or more answers are not recognised.", 400);
    }
  }

  // Consent must be an explicit true. Absent, false, or falsy values fail.
  if (submitted[SURVEY_CONSENT_ID] !== true) {
    return jsonError("Consent is required to submit a response.", 400);
  }

  // Respondent profile: optional fields are still validated when present.
  const profile: Record<string, SurveyAnswerValue> = {};
  const profileFieldErrors: Record<string, string> = {};
  for (const field of SURVEY_PROFILE_FIELDS) {
    const raw = submitted[field.id];
    if (raw === undefined) {
      if (field.required) {
        profileFieldErrors[field.id] = "This field is required.";
      }
      continue;
    }

    if (field.type === "select") {
      if (
        typeof raw !== "string" ||
        !field.options?.some((option) => option.value === raw)
      ) {
        profileFieldErrors[field.id] = "Please choose one of the listed options.";
        continue;
      }
      profile[field.id] = raw;
      continue;
    }

    if (typeof raw !== "string") {
      profileFieldErrors[field.id] = "Please answer using text.";
      continue;
    }
    const trimmed = raw.trim();
    if (
      field.maxLength && trimmed.length > field.maxLength
    ) {
      profileFieldErrors[field.id] = `Please use ${field.maxLength} characters or fewer.`;
      continue;
    }
    if (trimmed.length > MAX_PROFILE_TEXT_CHARS) {
      return jsonError("One or more answers are too long.", 400);
    }
    if (trimmed.length > 0) {
      profile[field.id] = trimmed;
    }
  }

  // Strict server-side validation of the 16 research questions against the
  // approved schema. Unknown ids, wrong types, and unlisted option values are
  // all rejected — JSONB does not make the payload trustworthy.
  const validated: Record<string, SurveyAnswerValue> = {};

  for (const question of surveyQuestions) {
    const raw = submitted[question.id];
    if (raw === undefined) continue;

    switch (question.type) {
      case "short-text":
      case "long-text": {
        if (typeof raw !== "string") {
          return jsonError("One or more answers have an invalid format.", 400);
        }
        const trimmed = raw.trim();
        if (question.maxLength && trimmed.length > question.maxLength) {
          return jsonError("One or more answers are too long.", 400);
        }
        validated[question.id] = trimmed;
        break;
      }
      case "single-choice": {
        if (
          typeof raw !== "string" ||
          !question.options?.some((option) => option.value === raw)
        ) {
          return jsonError("One or more answers have an invalid format.", 400);
        }
        validated[question.id] = raw;
        break;
      }
      case "multiple-choice": {
        if (
          !Array.isArray(raw) ||
          raw.length === 0 ||
          raw.length > MAX_CHOICE_COUNT ||
          raw.some((value) => typeof value !== "string")
        ) {
          return jsonError("One or more answers have an invalid format.", 400);
        }
        const allowedValues = new Set(
          question.options?.map((option) => option.value),
        );
        const unique = [...new Set(raw as string[])];
        if (unique.some((value) => !allowedValues.has(value))) {
          return jsonError("One or more answers have an invalid format.", 400);
        }
        validated[question.id] = unique;
        break;
      }
      case "yes-no": {
        if (typeof raw !== "boolean") {
          return jsonError("One or more answers have an invalid format.", 400);
        }
        validated[question.id] = raw;
        break;
      }
    }
  }

  const fieldErrors = {
    ...profileFieldErrors,
    ...validateSurveyAnswers(surveyQuestions, validated),
  };
  if (Object.keys(fieldErrors).length > 0) {
    return Response.json(
      {
        error: "Some required questions still need an answer.",
        fields: fieldErrors,
      },
      { status: 400 },
    );
  }

  let adminClient;
  try {
    adminClient = createAdminSupabaseClient();
  } catch {
    // Configuration problem: actionable but free of secret values.
    return jsonError(
      "The survey service is not configured yet. Set the Supabase environment variables (see the README).",
      503,
    );
  }

  // id and created_at are generated by the database. Answers are keyed by
  // stable question ids (never array positions).
  const { error } = await adminClient
    .from("survey_submissions")
    .insert({
      answers: {
        ...profile,
        [SURVEY_CONSENT_ID]: true,
        ...validated,
      },
      schema_version: SURVEY_SCHEMA_VERSION,
    });

  if (error) {
    // No details are logged or returned; the response is intentionally generic.
    return jsonError(
      "Your response could not be saved. Please try again in a moment.",
      500,
    );
  }

  return Response.json({ ok: true }, { status: 201 });
}
